function generateDiagnosticCode(mapping: ColumnMapping): GeneratedCode {
  const sections: CodeSection[] = [];
  
  const tp = mapping.tp || 'tp';
  const fp = mapping.fp || 'fp';
  const fn = mapping.fn || 'fn';
  const tn = mapping.tn || 'tn';
  const study = mapping.study || 'study';
  
  sections.push({
    title: 'Setup',
    description: 'Load required packages for diagnostic meta-analysis',
    code: `# ============================================
# Diagnostic Test Accuracy Meta-Analysis
# Generated by Glass Orchestrator
# ============================================

library(mada)
library(metafor)

# Load your data
# dat <- read.csv("your_data.csv")
`
  });
  
  sections.push({
    title: 'Prepare Data',
    description: 'Format 2x2 table data',
    code: `# ============================================
# Prepare Data
# ============================================

# Ensure data has correct column names for mada package
dat_mada <- data.frame(
  TP = dat$${tp},
  FP = dat$${fp},
  FN = dat$${fn},
  TN = dat$${tn}
)

# Calculate sensitivity and specificity for each study
dat_mada$sens <- dat_mada$TP / (dat_mada$TP + dat_mada$FN)
dat_mada$spec <- dat_mada$TN / (dat_mada$TN + dat_mada$FP)

print(dat_mada)
`
  });
  
  sections.push({
    title: 'Bivariate Model',
    description: 'Fit bivariate random-effects model',
    code: `# ============================================
# Bivariate Model (Reitsma et al.)
# ============================================

# Fit bivariate model
fit <- reitsma(dat_mada)
summary(fit)

# Summary operating point (pooled sensitivity and specificity)
cat("\\nSummary Operating Point:\\n")
cat(sprintf("Sensitivity: %.3f (95%% CI: %.3f - %.3f)\\n", 
            fit$coefficients[1,1], fit$coefficients[1,3], fit$coefficients[1,4]))
cat(sprintf("Specificity: %.3f (95%% CI: %.3f - %.3f)\\n",
            fit$coefficients[2,1], fit$coefficients[2,3], fit$coefficients[2,4]))

# Positive and negative likelihood ratios
sens <- fit$coefficients[1,1]
spec <- fit$coefficients[2,1]
lr_pos <- sens / (1 - spec)
lr_neg <- (1 - sens) / spec
cat(sprintf("\\nLR+: %.2f\\n", lr_pos))
cat(sprintf("LR-: %.2f\\n", lr_neg))
`
  });
  
  sections.push({
    title: 'SROC Curve',
    description: 'Summary ROC curve with confidence region',
    code: `# ============================================
# SROC Curve
# ============================================

# SROC curve with individual studies
plot(fit, 
     sroclwd = 2,
     main = "Summary ROC Curve")
points(1 - dat_mada$spec, dat_mada$sens, pch = 19)

# SROC curve with confidence and prediction regions
plot(fit, 
     sroclwd = 2,
     predict = TRUE,
     main = "SROC Curve with Prediction Region")
points(1 - dat_mada$spec, dat_mada$sens, pch = 19)
`
  });
  
  sections.push({
    title: 'Forest Plots',
    description: 'Paired forest plots for sensitivity and specificity',
    code: `# ============================================
# Forest Plots
# ============================================

# Forest plot - Sensitivity
forest(fit, type = "sens", main = "Sensitivity")

# Forest plot - Specificity
forest(fit, type = "spec", main = "Specificity")
`
  });
  
  sections.push({
    title: 'Heterogeneity',
    description: 'Assess heterogeneity in diagnostic accuracy',
    code: `# ============================================
# Heterogeneity Assessment
# ============================================

# Cochran's Q for sensitivity
sens_dat <- escalc(measure = "PLO", xi = dat_mada$TP, ni = dat_mada$TP + dat_mada$FN)
res_sens <- rma(yi, vi, data = sens_dat)
cat(sprintf("Sensitivity I²: %.1f%%\\n", res_sens$I2))

# Cochran's Q for specificity
spec_dat <- escalc(measure = "PLO", xi = dat_mada$TN, ni = dat_mada$TN + dat_mada$FP)
res_spec <- rma(yi, vi, data = spec_dat)
cat(sprintf("Specificity I²: %.1f%%\\n", res_spec$I2))
`
  });
  
  const script = sections.map(s => s.code).join('\n\n');
  
  return {
    script,
    sections,
    packages: ['mada', 'metafor']
  };
}

function generatePrecalculatedCode(
  mapping: ColumnMapping,
  measure: EffectMeasure
): GeneratedCode {
  const sections: CodeSection[] = [];
  
  const es = mapping.effect_size || 'effect_size';
  const se = mapping.se || 'se';
  const study = mapping.study || 'study';
  const needsTransform = ['OR', 'RR', 'HR'].includes(measure);
  
  sections.push({
    title: 'Setup',
    description: 'Load required packages',
    code: `# ============================================
# Meta-Analysis of Pre-calculated Effect Sizes
# Generated by Glass Orchestrator
# ============================================

library(metafor)

# Load your data
# dat <- read.csv("your_data.csv")
`
  });
  
  if (needsTransform) {
    sections.push({
      title: 'Transform Effect Sizes',
      description: `Transform ${measure} to log scale`,
      code: `# ============================================
# Transform Effect Sizes
# ============================================

# Transform to log scale for pooling
dat$yi <- log(dat$${es})
dat$sei <- dat$${se}

# For ratio measures, SE on log scale can be approximated from CI
# dat$sei <- (log(dat$ci_upper) - log(dat$ci_lower)) / (2 * 1.96)
`
    });
  }
  
  sections.push({
    title: 'Fit Random-Effects Model',
    description: 'Pool effect sizes using REML estimation',
    code: `# ============================================
# Fit Random-Effects Model
# ============================================

# Fit random-effects model
res <- rma(${needsTransform ? 'yi, sei = sei' : `yi = ${es}, sei = ${se}`}, 
           data = dat, 
           method = "REML",
           slab = ${study})

# Summary of results
summary(res)

# Pooled effect${needsTransform ? ' (back-transformed)' : ''}
predict(res${needsTransform ? ', transf = exp' : ''}, digits = 3)
`
  });
  
  sections.push({
    title: 'Forest Plot',
    description: 'Visualize individual and pooled effects',
    code: `# ============================================
# Forest Plot
# ============================================

# Forest plot
forest(res,
       ${needsTransform ? 'atransf = exp,' : ''}
       header = TRUE,
       slab = dat$${study},
       addpred = TRUE)
`
  });
  
  sections.push({
    title: 'Heterogeneity & Publication Bias',
    description: 'Assess heterogeneity and publication bias',
    code: `# ============================================
# Heterogeneity & Publication Bias
# ============================================

# Heterogeneity
cat(sprintf("I² = %.1f%%, τ² = %.4f\\n", res$I2, res$tau2))

# Funnel plot
funnel(res)

# Egger's test
regtest(res)

# Trim-and-fill
taf <- trimfill(res)
summary(taf)
`
  });
  
  const script = sections.map(s => s.code).join('\n\n');
  
  return {
    script,
    sections,
    packages: ['metafor']
  };
}

