/**
 * RCodeGenerator Module
 * 
 * Generates complete, executable R code for meta-analysis
 * based on data type and column mappings.
 */

import {
  DataType,
  AnalysisSuggestion,
  EffectMeasure,
  ColumnMapping,
  GeneratedCode,
  CodeSection
} from './types';
import { getEffectMeasureName } from './analysis-suggester';

/**
 * Generate complete R code for meta-analysis
 */
export function generateRCode(
  suggestion: AnalysisSuggestion,
  mapping: ColumnMapping,
  measure: EffectMeasure = suggestion.defaultMeasure
): GeneratedCode {
  switch (suggestion.dataType) {
    case DataType.BINARY:
      return generateBinaryCode(mapping, measure);
    
    case DataType.CONTINUOUS:
      return generateContinuousCode(mapping, measure);
    
    case DataType.PRECALCULATED:
      return generatePrecalculatedCode(mapping, measure);
    
    case DataType.DIAGNOSTIC:
      return generateDiagnosticCode(mapping);
    
    case DataType.CORRELATION:
      return generateCorrelationCode(mapping);
    
    case DataType.HAZARD_RATIO:
      return generateHazardRatioCode(mapping);
    
    default:
      return {
        script: '# Unable to generate code for unknown data type',
        sections: [],
        packages: []
      };
  }
}

function generateBinaryCode(
  mapping: ColumnMapping,
  measure: EffectMeasure
): GeneratedCode {
  const sections: CodeSection[] = [];
  
  const eventsT = mapping.events_treatment || 'events_treatment';
  const eventsC = mapping.events_control || 'events_control';
  const nT = mapping.n_treatment || 'n_treatment';
  const nC = mapping.n_control || 'n_control';
  const study = mapping.study || 'study';
  
  sections.push({
    title: 'Setup',
    description: 'Load required packages',
    code: `# ============================================
# Meta-Analysis of Binary Outcomes
# Generated by Glass Orchestrator
# ============================================

library(metafor)

# Load your data
# dat <- read.csv("your_data.csv")
`
  });
  
  sections.push({
    title: 'Calculate Effect Sizes',
    description: `Calculate ${measure} (${getEffectMeasureName(measure)}) and variance for each study`,
    code: `# ============================================
# Calculate Effect Sizes
# ============================================

# Calculate ${measure} (${getEffectMeasureName(measure)})
dat <- escalc(
  measure = "${measure}",
  ai = ${eventsT},
  bi = ${nT} - ${eventsT},
  ci = ${eventsC},
  di = ${nC} - ${eventsC},
  data = dat,
  slab = ${study}
)

# View calculated effect sizes
print(dat[, c("${study}", "yi", "vi")])
`
  });
  
  sections.push({
    title: 'Fit Random-Effects Model',
    description: 'Pool effect sizes using REML estimation',
    code: `# ============================================
# Fit Random-Effects Model
# ============================================

# Fit random-effects model
res <- rma(yi, vi, data = dat, method = "REML")

# Summary of results
summary(res)

# Pooled effect on original scale
predict(res, transf = exp, digits = 3)
`
  });
  
  sections.push({
    title: 'Forest Plot',
    description: 'Visualize individual and pooled effects',
    code: `# ============================================
# Forest Plot
# ============================================

# Forest plot
forest(res,
       atransf = exp,
       at = log(c(0.25, 0.5, 1, 2, 4)),
       xlim = c(-8, 6),
       header = TRUE,
       slab = dat$${study})

# Add prediction interval to forest plot
forest(res,
       atransf = exp,
       at = log(c(0.25, 0.5, 1, 2, 4)),
       xlim = c(-8, 6),
       header = TRUE,
       slab = dat$${study},
       addpred = TRUE)
`
  });
  
  sections.push({
    title: 'Heterogeneity Assessment',
    description: 'Assess between-study variability',
    code: `# ============================================
# Heterogeneity Assessment
# ============================================

cat("\\nHeterogeneity Assessment:\\n")
cat(sprintf("Q = %.2f, df = %d, p = %.4f\\n", res$QE, res$k - 1, res$QEp))
cat(sprintf("I² = %.1f%%\\n", res$I2))
cat(sprintf("τ² = %.4f (SE = %.4f)\\n", res$tau2, res$se.tau2))
cat(sprintf("τ = %.4f\\n", sqrt(res$tau2)))

# Prediction interval (95%)
pi <- predict(res, transf = exp)
cat(sprintf("\\n95%% Prediction Interval: %.2f to %.2f\\n", pi$pi.lb, pi$pi.ub))

# Interpretation
if (res$I2 < 25) {
  cat("\\nInterpretation: Low heterogeneity\\n")
} else if (res$I2 < 75) {
  cat("\\nInterpretation: Moderate heterogeneity\\n")
} else {
  cat("\\nInterpretation: High heterogeneity - consider subgroup analysis\\n")
}
`
  });
  
  sections.push({
    title: 'Publication Bias Assessment',
    description: "Funnel plot and Egger's test",
    code: `# ============================================
# Publication Bias Assessment
# ============================================

# Funnel plot
funnel(res, main = "Funnel Plot")

# Contour-enhanced funnel plot
funnel(res, level = c(90, 95, 99), shade = c("white", "gray55", "gray75"),
       refline = 0, legend = TRUE)

# Egger's regression test for funnel plot asymmetry
regtest(res)

# Rank correlation test (Begg's test)
ranktest(res)

# Trim-and-fill analysis
taf <- trimfill(res)
summary(taf)
cat(sprintf("\\nTrim-and-fill: %d studies imputed\\n", taf$k0))

# Funnel plot with imputed studies
funnel(taf, main = "Trim-and-Fill Funnel Plot")
`
  });
  
  sections.push({
    title: 'Sensitivity Analyses',
    description: 'Leave-one-out and influence diagnostics',
    code: `# ============================================
# Sensitivity Analyses
# ============================================

# Leave-one-out analysis
loo <- leave1out(res, transf = exp)
print(loo)

# Influence diagnostics
inf <- influence(res)
plot(inf)

# Baujat plot (contribution to heterogeneity vs influence)
baujat(res)
`
  });
  
  const script = sections.map(s => s.code).join('\n\n');
  
  return {
    script,
    sections,
    packages: ['metafor']
  };
}

